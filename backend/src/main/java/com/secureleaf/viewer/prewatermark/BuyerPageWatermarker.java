package com.secureleaf.viewer.prewatermark;

import com.secureleaf.commerce.entity.Entitlement;
import com.secureleaf.commerce.entity.EntitlementStatus;
import com.secureleaf.commerce.repository.EntitlementRepository;
import com.secureleaf.common.config.MinioProperties;
import com.secureleaf.common.storage.StorageService;
import com.secureleaf.content.entity.ContentPage;
import com.secureleaf.content.repository.ContentPageRepository;
import com.secureleaf.content.watermark.WatermarkRenderer;
import com.secureleaf.viewer.entity.BuyerPage;
import com.secureleaf.viewer.metrics.ViewerMetrics;
import com.secureleaf.viewer.repository.BuyerPageRepository;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Renders and stores one entitlement's missing pre-watermarked pages (every page, every variant of
 * the version it is pinned to). Called by {@link BuyerPageReconciler}; idempotent and resumable at
 * page granularity, because the work list is "page rows of the version minus pages already stored".
 *
 * <p>Per page: fetch the clean tile, watermark it, PUT the object, THEN insert the row. Object first,
 * row second: a crash between the two leaves an orphan object that the next run overwrites (same
 * deterministic key). The other order could leave a row pointing at nothing, and the view path
 * would then fail instead of falling back.
 *
 * <p>No transaction is held across a render: the page list is read in one short transaction, each
 * row is inserted in its own, and the CPU-heavy part runs with no database connection checked out.
 */
@Service
@Slf4j
public class BuyerPageWatermarker {

    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("yyyy-MM-dd");

    private final EntitlementRepository entitlementRepository;
    private final ContentPageRepository contentPageRepository;
    private final BuyerPageRepository buyerPageRepository;
    private final StorageService storageService;
    private final WatermarkRenderer watermarkRenderer;
    private final MinioProperties minioProperties;
    private final ViewerMetrics metrics;
    private final TransactionTemplate tx;
    private final String watermarkVersion;

    public BuyerPageWatermarker(EntitlementRepository entitlementRepository,
                                ContentPageRepository contentPageRepository,
                                BuyerPageRepository buyerPageRepository,
                                StorageService storageService,
                                WatermarkRenderer watermarkRenderer,
                                MinioProperties minioProperties,
                                ViewerMetrics metrics,
                                PlatformTransactionManager transactionManager,
                                @Value("${drm.prewatermark.version:1}") String watermarkVersion) {
        this.entitlementRepository = entitlementRepository;
        this.contentPageRepository = contentPageRepository;
        this.buyerPageRepository = buyerPageRepository;
        this.storageService = storageService;
        this.watermarkRenderer = watermarkRenderer;
        this.minioProperties = minioProperties;
        this.metrics = metrics;
        this.tx = new TransactionTemplate(transactionManager);
        this.watermarkVersion = watermarkVersion;
    }

    /** What one run needs, read in a single short transaction (the entities are lazy). */
    record Work(Long entitlementId, Long versionId, String label, List<PageSource> missing) {}

    record PageSource(int pageNumber, String variant, String bucket, String key) {}

    /** @return how many pages were generated by this call (0 if nothing was missing). */
    public int generate(Long entitlementId) {
        Work work = tx.execute(status -> plan(entitlementId));
        if (work == null || work.missing().isEmpty()) {
            return 0;
        }
        String bucket = minioProperties.getBucket().getTiles();
        int generated = 0;
        for (PageSource page : work.missing()) {
            byte[] clean = storageService.get(page.bucket(), page.key());
            byte[] watermarked = watermarkRenderer.applyWatermark(clean, work.label());
            String objectKey = objectKey(work, page);
            storageService.put(bucket, objectKey, watermarked, "image/png");
            if (insertRow(work, page, bucket, objectKey, watermarked.length)) {
                generated++;
                metrics.recordPrewatermarkGenerated();
            }
        }
        log.info("Pre-watermarked {} page(s) for entitlement {} (version {})", generated, work.entitlementId(), work.versionId());
        return generated;
    }

    private Work plan(Long entitlementId) {
        Entitlement entitlement = entitlementRepository.findById(entitlementId).orElse(null);
        if (entitlement == null || entitlement.getStatus() != EntitlementStatus.ACTIVE) {
            return null;
        }
        Long versionId = entitlement.getDocumentVersion().getId();
        Set<String> done = buyerPageRepository
                .findByEntitlementIdAndDocumentVersionIdAndWatermarkVersion(entitlementId, versionId, watermarkVersion)
                .stream()
                .map(p -> p.getPageNumber() + "/" + p.getVariant())
                .collect(Collectors.toSet());
        List<PageSource> missing = contentPageRepository.findByDocumentVersionIdOrderByPageNumber(versionId).stream()
                .filter(cp -> !done.contains(cp.getPageNumber() + "/" + cp.getVariant()))
                .map(BuyerPageWatermarker::source)
                .toList();
        return new Work(entitlementId, versionId, label(entitlement), missing);
    }

    private static PageSource source(ContentPage cp) {
        return new PageSource(cp.getPageNumber(), cp.getVariant(), cp.getBucketName(), cp.getMinioObjectKey());
    }

    /**
     * "{email} · #{userId} · {purchase date} UTC · e{entitlementId}". There is no viewer session at
     * purchase time, so the session id of the live watermark becomes the entitlement id: it still
     * leads to exactly one purchase (entitlement -> order -> payment). The exact time of every page
     * view stays in viewer_access_logs, as before.
     */
    static String label(Entitlement entitlement) {
        return "%s · #%d · %s UTC · e%d".formatted(
                entitlement.getBuyer().getEmail(),
                entitlement.getBuyer().getId(),
                DATE.format(entitlement.getGrantedAt().atZone(ZoneOffset.UTC)),
                entitlement.getId());
    }

    /** Deterministic, so a retried page overwrites its own orphan instead of leaving a second one.
     *  The watermark version is in the path: regenerated pages never overwrite stale ones that the
     *  cleanup sweep is about to delete. */
    private String objectKey(Work work, PageSource page) {
        return "buyers/%d/v%d/w%s/%s/page-%d.png".formatted(
                work.entitlementId(), work.versionId(), watermarkVersion, page.variant(), page.pageNumber());
    }

    /** @return false if another run inserted the same page first (unique constraint): not an error. */
    private boolean insertRow(Work work, PageSource page, String bucket, String objectKey, int size) {
        try {
            tx.executeWithoutResult(status -> {
                BuyerPage row = new BuyerPage();
                row.setEntitlementId(work.entitlementId());
                row.setDocumentVersionId(work.versionId());
                row.setPageNumber(page.pageNumber());
                row.setVariant(page.variant());
                row.setWatermarkVersion(watermarkVersion);
                row.setBucketName(bucket);
                row.setObjectKey(objectKey);
                row.setFileSizeBytes((long) size);
                row.setCreatedAt(Instant.now());
                buyerPageRepository.saveAndFlush(row);
            });
            return true;
        } catch (DataIntegrityViolationException duplicate) {
            return false;
        }
    }
}
